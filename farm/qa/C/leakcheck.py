#!/usr/bin/env python3
"""Experiment C: leak check for the scores-only prompts (docs/qa_week/C_PREREG.md, "Leak check").

For each scores-only prompt P and the full prompt O it was derived from (regenerated by the A32/A35 code, which reproduces
the committed A32/A35 prompt files byte for byte), PASS requires all of:
  1 structure  every HISTORY line is a run head line, a "  setting {...}" line, a score line in the fixed template, or
               (proposer rounds 2-4) "  (your rationale then: ...)"; nothing else (no report line can hide anywhere)
  2 report     no line of P starts with a report prefix, and no report vocabulary appears in P outside the fixed GOAL /
               KNOBS text that O also has
  3 provenance every line of P is either verbatim in O, a score line, or one of the three edited sentences
  4 scores     each score line's numbers equal what TPE is told about that run (recomputed from the state records)
  5 later      no run tag other than the tags O itself shows; no tag pattern of any later run (A35/A36/A32 arms, closures,
               chains, this experiment's own runs except the arm's own history); no outcome file names or result words
Design names are present on purpose (g's and a's prompts had them; removing them would change two things at once).
Usage: leakcheck.py [--json out.json]   (checks every prompt listed in farm/qa/C/prompts/MANIFEST.json)
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import clib as C  # noqa: E402

SCORE_RE = re.compile(r"^  scores: constraints \[router DRC errors, minus the worst hold slack \(ns\), slew/cap pins minus the bar\] = "
                      r"\[(?P<a>-?[0-9.]+), (?P<b>[+-][0-9.]+), (?P<c>-?[0-9.]+)\]; FEASIBLE only if all three are <= 0$")
SCORE_FAIL_RE = re.compile(r"^  scores: no result; the optimizer is told T_eff (?P<t>[0-9.]+) ns \(twice the default clock\) and "
                           r"constraints \[(?P<a>-?[0-9.]+), (?P<b>-?[0-9.]+), (?P<c>-?[0-9.]+)\]$")
SETTING_RE = re.compile(r"^  setting \{.*\}$")
RATIONALE_RE = re.compile(r"^  \(your rationale then: .*\)$")
REPORT_WORDS = ["worst slack", "reg-to-reg", "TNS", "violating endpoints", "hold buffers", "timing-repair buffers",
                "std-cell area", "std cells", "wirelength", "pre-route estimate", "detailed-route DRC", "skew", " mW",
                "flow runtime", "max-slew", "max-cap", "fanout violations", "touches an input/output port",
                "run stopped before signoff", "last error", "100C", "-40C", "max-RC", "min-RC", "nom-RC", "signoff summar"]
LATER_TAGS = re.compile(r"\b(?:xa[bfgh][12]|xak|xac|xaqk|xaqc|xazk|xazc|xayk|xayc|xaz|xay|xar|xam|xao|xap|xax|x8[abfkcs]|"
                        r"x9[a-z]|xm[a-z0-9]*|xn[a-z0-9]*|e5[a-z]|smoke)-[A-Za-z0-9_]+(?:-[0-9]+)*")
OUTCOME_WORDS = ["state.json", "metrics.json", "report_a3", "RESULT", "results/", "PREREG", "fixed point", "fixed-point",
                 "kept clock", "decision record", "Decision record", "A35", "A36", "A32", "A33", "Addendum", "rebuild"]


def history_block(text):
    i = text.index("HISTORY on this design")
    j = text.index("\nTASK. ")
    return text[i:j].split("\n")[2:]       # skip the two header lines


def check(p_text, o_text, views, own_tags=()):
    errs = []
    try:
        hist = [l for l in history_block(p_text) if l.strip()]
    except ValueError:
        hist = []
        errs.append("structure: the HISTORY or TASK section markers are missing or moved")
    # 1 structure
    for l in hist:
        if C.HEAD.match(l) or SETTING_RE.match(l) or SCORE_RE.match(l) or SCORE_FAIL_RE.match(l) or RATIONALE_RE.match(l):
            continue
        if l.startswith("POLICIES SO FAR"):
            continue
        errs.append(f"structure: unexpected HISTORY line: {l[:100]}")
    # 2 report lines and vocabulary
    for l in p_text.split("\n"):
        if l.startswith(C.REPORT_PREFIXES):
            errs.append(f"report line present: {l[:80]}")
    # the arm's own earlier rationales are its own words (it never saw a report), so they are not scanned for vocabulary;
    # they are still held to the structure, provenance and later-tag checks
    body = "\n".join(l for l in hist if not (SCORE_RE.match(l) or SCORE_FAIL_RE.match(l) or RATIONALE_RE.match(l)))
    for w in REPORT_WORDS:
        if w in body:
            errs.append(f"report vocabulary in HISTORY: {w!r}")
    for w in REPORT_WORDS:                          # anywhere else: only if the fixed text of O has it too
        if w in p_text and w not in o_text and w not in body:
            errs.append(f"report vocabulary outside HISTORY not in the original: {w!r}")
    # 3 provenance
    o_edit = o_text
    for pat, rep in C.EDITS:
        o_edit = re.sub(pat, rep, o_edit)
    o_lines = set(o_text.split("\n")) | set(o_edit.split("\n"))     # verbatim, or verbatim after the three edits
    for l in p_text.split("\n"):
        if l in o_lines or SCORE_RE.match(l) or SCORE_FAIL_RE.match(l):
            continue
        errs.append(f"provenance: line not in the original: {l[:100]}")
    # 4 score values
    cur = None
    for l in p_text.split("\n"):
        m = C.HEAD.match(l)
        if m:
            cur = m.group("tag")
            continue
        ms, mf = SCORE_RE.match(l), SCORE_FAIL_RE.match(l)
        if not (ms or mf):
            continue
        v = views.get(cur)
        if v is None:
            errs.append(f"scores: no state record for {cur}")
            continue
        got = [float((ms or mf).group(k)) for k in "abc"]
        if any(abs(g - c) > 0.0006 for g, c in zip(got, v["cons"])):
            errs.append(f"scores: {cur} shows {got}, state has {v['cons']}")
        if mf and abs(float(mf.group("t")) - v["penalty"]) > 0.0006:
            errs.append(f"scores: {cur} penalty {mf.group('t')} != {v['penalty']}")
        if ms and v["teff"] is None:
            errs.append(f"scores: {cur} has no T_eff but a feasible-style line")
    # 5 later results
    o_tags = set(m.group("tag") for m in map(C.HEAD.match, o_text.split("\n")) if m)
    p_tags = set(m.group("tag") for m in map(C.HEAD.match, p_text.split("\n")) if m)
    if not p_tags <= o_tags:
        errs.append(f"later: tags not in the original: {sorted(p_tags - o_tags)}")
    for m in LATER_TAGS.finditer(p_text):
        if m.group(0) not in own_tags:
            errs.append(f"later: run tag of a later run: {m.group(0)}")
    for w in OUTCOME_WORDS:
        if w in p_text and w not in o_text:
            errs.append(f"later: outcome word not in the original: {w!r}")
    designs = {d: p_text.count(d) for d in sorted(set(C.RULE_DESIGNS + C.PROP_DESIGNS)) if d in p_text}
    return errs, designs


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=None)
    a = ap.parse_args()
    man = json.load(open(os.path.join(C.REPO_PROMPTS, "MANIFEST.json")))
    out, bad = [], 0
    for e in man["prompts"]:
        p_path = os.path.join(C.ROOT, e["repo_path"])
        p_text = open(p_path).read()
        if e["kind"] == "rule":
            o_text = C.rule_prompt_full(e["design"], e["seed"])
            assert o_text == open(os.path.join(C.ROOT, e["original"])).read(), e["original"]
            views, own = C.rule_views(e["design"]), ()
        else:
            d = e["design"]
            st = C.A.load(e["state"], {"tags": {}}) if e.get("state") else {"tags": {}}
            own = tuple(t for t, v in st["tags"].items() if v["design"] == d and v["arm"] == "p")
            if e["round"] == 1:
                o_text, views = C.prop_prompt_full({"tags": {}}, d, 1)
                assert o_text == open(os.path.join(C.ROOT, e["original"])).read(), e["original"]
            else:   # rounds 2-4: the report-bearing original saved when the prompt was written (the state moves on)
                o_text = open(os.path.join(C.ROOT, e["original"])).read()
                views = C.views_for([(t, v) for t, v, _ in C.B.start_set(d)] +
                                    [(t, v) for t, v in st["tags"].items() if v["design"] == d and v["arm"] == "p"],
                                    C.B.HELD[d])
        errs, designs = check(p_text, o_text, views, own)
        try:
            if C.scores_only(o_text, views)[0] != p_text:
                errs.append("the prompt is not the registered transform of its original")
        except Exception as ex:  # noqa: BLE001
            errs.append(f"transform could not be re-applied: {ex}")
        mirror = e.get("ideas_path")
        if mirror and (not os.path.exists(mirror) or open(mirror).read() != p_text):
            errs.append(f"hand-off copy missing or different: {mirror}")
        if C.sha256(p_path) != e["sha256"]:
            errs.append("sha256 differs from MANIFEST")
        bad += bool(errs)
        out.append({"prompt": e["repo_path"], "ok": not errs, "errors": errs, "design_names": designs,
                    "report_lines_in_original": sum(1 for l in o_text.split("\n") if l.startswith(C.REPORT_PREFIXES)),
                    "report_lines_in_prompt": sum(1 for l in p_text.split("\n") if l.startswith(C.REPORT_PREFIXES))})
        print(f"{'PASS' if not errs else 'FAIL'}  {e['repo_path']}  (original report lines "
              f"{out[-1]['report_lines_in_original']}, left {out[-1]['report_lines_in_prompt']}; design names {designs})")
        for x in errs:
            print(f"      {x}")
    print(f"leak check: {'PASS' if not bad else 'FAIL'} ({len(out) - bad} of {len(out)} prompts clean)")
    if a.json:
        json.dump({"ok": not bad, "prompts": out}, open(a.json, "w"), indent=1)
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
